#include <iostream>

int main() {
    int a = 17;
    int b = 5;

    std::cout << "a + b: " << a + b << '\n';
    std::cout << "a - b: " << a - b << '\n';
    std::cout << "a * b: " << a * b << '\n';
    std::cout << "a / b: " << a / b << '\n';
    std::cout << "a % b: " << a % b << '\n';
    return 0;
}
